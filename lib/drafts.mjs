// Outlines are deterministic: the draft builder makes no model calls, remote
// API calls, or network requests. Optional local AI lives in lib/ai/.
export function buildDraft({ kind, title, params, project, resources, settings, author }) {
  const sources = resources.map((r, i) => `[${i + 1}] ${r.name}${r.kind === 'template' ? ' (company template)' : ''}`);
  if (kind === 'memo') {
    const template = resources.find(r => r.kind === 'template' && r.text);
    const templateHeadings = template?.text.match(/^#{1,3}\s+.+$/gm)?.map(x => x.replace(/^#+\s+/, '').trim()).slice(0, 20);
    const settingHeadings = settings?.memoHeadings?.split('\n').map(x => x.trim()).filter(Boolean);
    const headings = templateHeadings?.length ? templateHeadings : settingHeadings?.length ? settingHeadings : DEFAULT_MEMO_HEADINGS;
    const memo = buildMemo({ params, project, headings, author });
    return { body: composeMemo({ title, memo, project, gaap: params.gaap }), memo, mode: 'outline', warnings: ['Working outline. Content must be completed and reviewed by your team.'] };
  }
  const area = params.area || params.deckType;
  const body = `# ${title}\n\n## ${title}\n- ${project.client}\n- ${params.deckType} · ${area}\n- Financial year end: ${project.fy}\n\n## The brief\n- ${params.problem}\n- Audience: ${params.audience || 'Client stakeholders'}\n\n## Engagement context\n- Workstream: ${area}\n${params.ipoTrack ? `- IPO focus: ${params.ipoTrack}\n` : ''}${params.currentGaap ? `- Current framework: ${params.currentGaap}\n- Target framework: ${params.targetGaap}\n- Current methodologies: ${params.methodologies || '[Confirm with management]'}\n` : ''}- [Validate background and business objectives]\n\n## Approach\n- [Define the proposed approach]\n- [Agree scope, dependencies, and milestones]\n\n## Deliverables and workstreams\n- [Define the engagement deliverables]\n- [Assign workstream owners and review milestones]\n\n## Timeline and team\n- [Insert agreed phases, dates, and responsibilities]\n- [Confirm client and advisory team availability]\n\n## Project evidence\n${sources.map(s => `- ${s}`).join('\n') || '- No resources selected'}\n\n## Decisions and next steps\n- [Confirm scope and success criteria]\n- [Resolve open information requests]\n- Obtain engagement review before circulation`;
  return { body, mode: 'outline', warnings: ['Working outline. Content must be completed and reviewed by your team.'] };
}
